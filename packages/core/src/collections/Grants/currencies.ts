/** Select options labelled "BDT (Bangladeshi Taka)"; the label is display-only. */
export const CURRENCY_OPTIONS = CODES.map((code) => {
  const name = names.of(code)
  return { label: name && name !== code ? `${code} (${name})` : code, value: code }
})
